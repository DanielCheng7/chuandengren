/* ---------- 行构造助手 ---------- */
/**
 * 画面中央字卡：场景切换题注 / 画面描述 / 幕间提示 —— 居中渐隐 + 自动推进。
 * 玩家看到 `text`；`sceneTag`（场景 key）与 `scriptRaw`（含提示符号的剧本原文）仅审核模式拼回显示。
 * `item` 可选：带道具标记时改由「道具亮相」接管（居中字卡不叠显）。
 */
const caption = (
  text: string,
  sceneTag?: string,
  scriptRaw?: string,
  item?: ShowcaseItem
): Line => ({
  text,
  type: 'caption',
  sceneTag,
  scriptRaw,
  item,
})
const note = (text: string): Line => ({ text, type: 'note' })
/** 旁白（无人称动作句） */
const nar = (text: string): Line => ({ speaker: '旁白', text, type: 'narration' })
/** 旁白（知遥）＝ 第一人称「我…」；可选 `item` 让本行以「道具亮相」呈现 */
const inn = (text: string, item?: ShowcaseItem): Line => ({
  speaker: '知遥',
  text,
  type: 'narration',
  item,
})
const say = (speaker: Speaker, text: string): Line => ({ speaker, text, type: 'dialogue' })
/** 短信 / 旧信文字；可选 `item` 让本行在光雾中随道具一同呈现（信文用暖金色） */
const sms = (speaker: Speaker, text: string, item?: ShowcaseItem): Line => ({
  speaker,
  text,
  type: 'sms',
  item,
})

